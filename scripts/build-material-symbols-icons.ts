import { promises as fs } from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

import { logger } from './utils';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..');

const MANIFEST_PATH = path.join(
  REPO_ROOT,
  'libs/shared/utility/src/lib/material-symbols-icons.ts',
);
const WOFF2_PATH = path.join(
  REPO_ROOT,
  'apps/web/public/fonts/material-symbols/MaterialSymbolsOutlined-variable.woff2',
);

const SCAN_ROOTS = [
  path.join(REPO_ROOT, 'apps/web/src'),
  path.join(REPO_ROOT, 'libs'),
];

const SCAN_EXTENSIONS = new Set(['.html', '.ts']);

const EXCLUDE_PATTERNS: readonly RegExp[] = [
  /\.spec\.ts$/,
  /[\\/]node_modules[\\/]/,
  /[\\/]\.nx[\\/]/,
  /[\\/]dist[\\/]/,
  /material-symbols-icons\.ts$/, // anti-recursion
];

const ICON_PATTERNS: readonly RegExp[] = [
  /<mat-icon[^>]*>([a-z][a-z0-9_]*)<\/mat-icon>/g,
  /<kookio-icon[^>]*\bname="([a-z][a-z0-9_]*)"/g,
  /\bicon:\s*'([a-z][a-z0-9_]*)'/g,
  /\bicon="([a-z][a-z0-9_]*)"/g,
];

const GOOGLE_FONTS_CSS_BASE = 'https://fonts.googleapis.com/css2';
const FAMILY_PARAM =
  'Material Symbols Outlined:opsz,wght,FILL,GRAD@20..48,100..700,0..1,-50..200';
const MODERN_UA =
  'Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

type Args = { check: boolean };

const parseArgs = (): Args => ({
  check: process.argv.includes('--check'),
});

const walk = async (dir: string): Promise<string[]> => {
  const entries = await fs.readdir(dir, {
    withFileTypes: true,
    recursive: true,
  });
  return entries
    .filter((e) => e.isFile())
    .map((e) => path.join(e.parentPath ?? dir, e.name))
    .filter((f) => SCAN_EXTENSIONS.has(path.extname(f)))
    .filter((f) => !EXCLUDE_PATTERNS.some((p) => p.test(f)));
};

const scanFile = async (file: string): Promise<Set<string>> => {
  const content = await fs.readFile(file, 'utf8');
  const found = new Set<string>();
  for (const pattern of ICON_PATTERNS) {
    pattern.lastIndex = 0;
    let match: RegExpExecArray | null;
    while ((match = pattern.exec(content)) !== null) {
      found.add(match[1]);
    }
  }
  return found;
};

const scanCodebase = async (): Promise<Set<string>> => {
  const fileLists = await Promise.all(SCAN_ROOTS.map(walk));
  const allFiles = fileLists.flat();
  const all = new Set<string>();
  for (const file of allFiles) {
    const fromFile = await scanFile(file);
    for (const icon of fromFile) all.add(icon);
  }
  return all;
};

const readCommittedManifest = async (): Promise<Set<string>> => {
  try {
    const content = await fs.readFile(MANIFEST_PATH, 'utf8');
    const block =
      /export const MATERIAL_SYMBOLS_ICONS\s*=\s*\[([\s\S]*?)\]\s*as const/.exec(
        content,
      );
    if (!block) return new Set();
    const icons = [...block[1].matchAll(/'([a-z][a-z0-9_]*)'/g)].map(
      (m) => m[1],
    );
    return new Set(icons);
  } catch {
    return new Set();
  }
};

const setEquals = (a: Set<string>, b: Set<string>): boolean =>
  a.size === b.size && [...a].every((x) => b.has(x));

const writeManifest = async (icons: readonly string[]): Promise<void> => {
  const sorted = [...icons].sort();
  const lines = sorted.map((i) => `  '${i}',`).join('\n');
  const content = `// AUTO-GENERATED by scripts/build-material-symbols-icons.ts
// Do not edit by hand. Run: npm run build:icons
//
// MATERIAL_SYMBOLS_ICONS = runtime list, used for audit & iteration.
// MaterialSymbolName    = union type derived from the list above
//                         (standard TypeScript idiom, similar to
//                         Object.keys-based typing).
//
// Usage:
//   import type { MaterialSymbolName } from '@kookio/shared-utility';
//   const icon: MaterialSymbolName = 'account_circle';

export const MATERIAL_SYMBOLS_ICONS = [
${lines}
] as const;

export type MaterialSymbolName = (typeof MATERIAL_SYMBOLS_ICONS)[number];
`;

  await fs.mkdir(path.dirname(MANIFEST_PATH), { recursive: true });
  await fs.writeFile(MANIFEST_PATH, content, 'utf8');
};

const fetchSubsetWoff2 = async (icons: readonly string[]): Promise<Buffer> => {
  const sorted = [...icons].sort();
  const cssUrl = new URL(GOOGLE_FONTS_CSS_BASE);
  cssUrl.searchParams.set('family', FAMILY_PARAM);
  cssUrl.searchParams.set('icon_names', sorted.join(','));

  const cssResp = await fetch(cssUrl.toString(), {
    headers: { 'User-Agent': MODERN_UA },
  });
  if (!cssResp.ok) {
    throw new Error(`Google Fonts CSS fetch failed: ${cssResp.status}`);
  }
  const css = await cssResp.text();

  const woff2UrlMatch =
    /src:\s*url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/.exec(css);
  if (!woff2UrlMatch) {
    throw new Error('Could not parse woff2 URL from Google Fonts CSS');
  }
  const woff2Url = woff2UrlMatch[1];

  const fontResp = await fetch(woff2Url);
  if (!fontResp.ok) {
    throw new Error(`woff2 fetch failed: ${fontResp.status}`);
  }
  return Buffer.from(await fontResp.arrayBuffer());
};

const fileExists = async (p: string): Promise<boolean> => {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
};

const main = async (): Promise<void> => {
  const { check } = parseArgs();

  logger.info('Scanning codebase for icon usage...');
  const scanned = await scanCodebase();
  const current = await readCommittedManifest();
  const woff2Exists = await fileExists(WOFF2_PATH);

  const equal = setEquals(scanned, current);

  if (equal && woff2Exists) {
    logger.info(`✓ Icons up-to-date (${scanned.size} icons)`);
    return;
  }

  if (check) {
    logger.error('✗ Icon manifest out of date. Run: npm run build:icons');
    const added = [...scanned].filter((i) => !current.has(i)).sort();
    const removed = [...current].filter((i) => !scanned.has(i)).sort();
    if (added.length) logger.error(`  Added:   ${added.join(', ')}`);
    if (removed.length) logger.error(`  Removed: ${removed.join(', ')}`);
    if (!woff2Exists) logger.error('  Subset woff2 missing');
    process.exit(1);
  }

  if (!equal) {
    logger.info(`Writing manifest (${scanned.size} icons)...`);
    await writeManifest([...scanned]);
  }

  logger.info('Fetching subset woff2 from Google Fonts...');
  const woff2 = await fetchSubsetWoff2([...scanned]);
  await fs.mkdir(path.dirname(WOFF2_PATH), { recursive: true });
  await fs.writeFile(WOFF2_PATH, woff2);
  logger.info(`✓ Wrote subset woff2 (${(woff2.length / 1024).toFixed(1)} KB)`);
};

(async () => {
  try {
    await main();
  } catch (err) {
    logger.error(err);
    process.exit(1);
  }
})();
