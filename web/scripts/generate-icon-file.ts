import { readdir, mkdir, writeFile, stat } from 'node:fs/promises';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

import { logger } from '@kookio/server-logger';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

async function ensureDirExists(filePath: string) {
  const dir = path.dirname(filePath);
  await mkdir(dir, { recursive: true });
}

const args = process.argv.slice(2);
const nsArg = args.find(arg => arg.startsWith('--namespace='));
const namespace = nsArg?.split('=')[1];

if (!namespace) {
  logger.error('❌ Use param: --namespace=<namespace>');
  process.exit(1);
}

const ICONS_BASE_DIR = path.resolve(__dirname, `../../web/public/icons/${namespace}`);
const OUTPUT_FILE = path.resolve(__dirname, `../../web/src/app/icons/${namespace}-icons.ts`);
const CONST_NAME = `${namespace.toUpperCase()}_ICONS`;

async function collectIconMap(): Promise<Map<string, Set<string>>> {
  const map = new Map<string, Set<string>>();

  try {
    const styles = await readdir(ICONS_BASE_DIR);
    for (const style of styles) {
      const dir = path.join(ICONS_BASE_DIR, style);
      if (!(await stat(dir)).isDirectory()) continue;

      const files = await readdir(dir);
      for (const file of files) {
        if (!file.endsWith('.svg')) continue;

        const name = file.replace('.svg', '');
        if (!map.has(name)) map.set(name, new Set());
        map.get(name)?.add(style);
      }
    }
  } catch (err) {
    logger.error(err, `❌ Cannot read icons from: ${ICONS_BASE_DIR}`);
    process.exit(1);
  }

  return map;
}

async function generateIconNamespaceFile(namespace: string, iconMap: Map<string, Set<string>>) {
  const sorted = Array.from(iconMap.entries()).sort(([a], [b]) => a.localeCompare(b));
  const lines = [
    `/* This file is auto-generated by 'web/src/scripts/generate-icon-file.ts' */`,
    `/* Do not edit this file directly. Use one of following commands: */`,
    ``,
    `/* npx vite-node --config web/scripts/vite.config.ts web/scripts/generate-icon-file.ts --namespace=<namespace> */`,
    `/* npx nx <namespace>-icons:<style> if is configured in web/project.json */`,
    ``,
    `import { IconNamespace } from "./types";`,
    ``,
    `export const ${CONST_NAME}: IconNamespace[] = [`,
    `  {`,
    `    namespace: '${namespace}',`,
    `    icons: [`,
    ...sorted.map(([name, styles]) => {
      const list = Array.from(styles).map(s => `'${s}'`).join(', ');
      return `      { name: '${name}', styles: [${list}] },`;
    }),
    `    ]`,
    `  }`,
    `];`,
    ``
  ];

  await ensureDirExists(OUTPUT_FILE);
  await writeFile(OUTPUT_FILE, lines.join('\n'), 'utf-8');
  logger.info(`✅ ${namespace}-icons.ts created with ${sorted.length} entries.`);
}

(async () => {
  const iconMap = await collectIconMap();
  if (iconMap.size === 0) {
    logger.warn(`⚠️ No icons found for namespace '${namespace}'`);
    return;
  }

  await generateIconNamespaceFile(namespace, iconMap);
})();