import * as z from 'zod';
export const RecipeFindManyResultSchema = z.object({
  data: z.array(
    z.object({
      id: z.string(),
      externalId: z.string().optional(),
      slug: z.string(),
      title: z.string(),
      description: z.string().optional(),
      imageUrl: z.string().optional(),
      youtubeUrl: z.string().optional(),
      sourceUrl: z.string().optional(),
      instructions: z.string(),
      status: z.unknown(),
      servings: z.number().int(),
      prepTimeMinutes: z.number().int().optional(),
      cookTimeMinutes: z.number().int().optional(),
      categoryId: z.string().optional(),
      areaId: z.string().optional(),
      authorId: z.string().optional(),
      createdAt: z.date(),
      updatedAt: z.date(),
      category: z.unknown().optional(),
      area: z.unknown().optional(),
      author: z.unknown().optional(),
      ingredients: z.array(z.unknown()),
      tags: z.array(z.unknown()),
      collectionEntries: z.array(z.unknown()),
      mealPlanSlots: z.array(z.unknown()),
      cookingSessions: z.array(z.unknown()),
    }),
  ),
  pagination: z.object({
    page: z.number().int().min(1),
    pageSize: z.number().int().min(1),
    total: z.number().int().min(0),
    totalPages: z.number().int().min(0),
    hasNext: z.boolean(),
    hasPrev: z.boolean(),
  }),
});
